# Ejemplo 2: Desempaquetado de tuplas

# Se crea una tupa con información de un estudiante. 
estudiante = ("Dennis", 24, "ADSO")

# Se asigna cada elemento de la tupla a una variable. 
nombre, edad, programa = estudiante

print("Nombre:")
print(nombre)

print("\nEdad:")
print(edad)

print("\nPrograma:")
print(programa)

# ¿Qué hace este programa?

# Este programa muestra cómo desempquetar una tupla.
# Cada elemento de la tupla se almacena en una variable
# diferente utilizando una sola línea de código. 

# Esto facilita el acceso a los datos y hace que el 
# código sea más limpio y fácil de leer. 
