# Ejemplo 1: Creación y acceso a tuplas

# Se crea una tupla con información de un estudiante. 
estudiante =("Dennis", 24, "ADSO")

print("Tupla completa:")
print(estudiante)

# Se accede al primer elemento. 
print("\nNombre:")
print(estudiante[0])

# Se accede al segundo elemento.
print("\nEdad:")
print(estudiante[1])

# Se accede al último elemento. 
print("\nPrograma:")
print(estudiante[-1])

# Se muestra la cantidad de elementos. 
print("\nCantidad de elemento:")
print(len(estudiante))

# ¿Qué hace este programa?

# - Crear una tupla.
# - Acceder a sus elementos.
# - Utilizar índices positivos y negativos.
# - Obtener la cantidad de elementos.

# A diferencia de las listas, las tuplas son inmutables, 
# Es decir, no pueden modificarse después de su creación. 