# Se crea una lista con algunos lenguaje de progrmación.
lenguajes = ["Python", "Java", "C#"]

print("Lista inicial")
print(lenguajes)

# append() agrega un elemento al final de la lista. 
lenguajes.append("JavaScript")

print("\nDespués de append():")
print(lenguajes)

# insert() agrega un elemento en una posición específica. 
lenguajes.insert(1, "C++")

print("\nDespués de insert()")
print(lenguajes)

# extend() agrega varios elementos de otra lista.
lenguajes.extend(["PHP", "Kotlin"])

print("\nDespués de extend():")
print(lenguajes)

# ¿Qúe hace este programa?

# Este progra,a muestra tres métodos para agregar elementos a una lista: 

# append() -> agregar un solo elemento al final.
# insert() -> agrega un elemento e una posición específica. 
# extend() -> agrega varios elementos provenientes de otra lista. 



