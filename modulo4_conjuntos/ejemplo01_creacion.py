# Ejemplo 1: Creación de conjuntos

# Se crea un conjunto de colores.
colores = {"Rojo", "Azul", "Verde", "Amarillo"}

print("Conjunto completo:")
print(colores)

# Se muestra la cantidad de elementos.
print("\nCantidad de elementos:")
print(len(colores))

# Se verifica si un elemento pertenece al conjunto.
print("\n¿Existe el color Azul?")
print("Azul" in colores)

print("\n¿Existe el color Negro?")
print("Negro" in colores)

